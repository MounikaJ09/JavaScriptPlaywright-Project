//==,===,=
let a=5;
console.log(a);
//console.log(5=5); // This will cause a syntax error because the assignment operator (=) is used to assign a value to a variable, and it cannot be used in a comparison context. The correct operator for comparison is the equality operator (==) or the strict equality operator (===).
console.log(5==5); // This will output 'true' because the equality operator (==) checks for value equality, and both sides are equal.
console.log(5===5); // This will also output 'true' because the strict equality operator (===) checks for both value and type equality, and both sides are equal in value and type.         
